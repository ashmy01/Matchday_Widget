/* =============================================================
   Builds the self-contained Scriptable widget script that the user
   copies from the site and pastes into the Scriptable app on iOS.

   The generated script:
     • carries the user's choices (time zone, team colours, mode)
     • embeds the fixtures + team names/flags so it works offline
     • re-implements the SAME widget logic as the live preview
     • uses the phone's REAL current time, so it rolls forward by itself
     • light colour = border, dark colour = background
     • shows a REAL World Cup photo (CUP_IMAGE) you can swap for your own
   ============================================================= */

export function buildScript({ timeZone, team, mode, bgStyle, teams, fixtures, cupImage, matchLengthMin }) {
  const slim = fixtures.map((m) => ({ k: m.kickoff, h: m.home, a: m.away }));

  // live dot: bright red, but black on red backgrounds so it stays visible
  const reddish = (hex) => {
    const h = (hex || "").replace("#", "");
    const r = parseInt(h.slice(0, 2), 16), g = parseInt(h.slice(2, 4), 16), b = parseInt(h.slice(4, 6), 16);
    return r > 100 && r > g * 1.5 && r > b * 1.5;
  };

  const codes = new Set();
  fixtures.forEach((m) => { codes.add(m.home); codes.add(m.away); });
  const T = {};
  codes.forEach((c) => {
    const t = teams.find((x) => x.code === c);
    T[c] = t ? { n: t.name, f: t.flag } : { n: c, f: "" };
  });

  const cfg = {
    tz: timeZone,
    teamCode: team.code,
    teamName: team.name,
    bg: team.dark,
    border: team.light,
    fg: team.text,
    flag: `https://flagcdn.com/w160/${team.iso}.png`, // low-res -> upscaled => blurred bg
    bgStyle: bgStyle === "solid" ? "solid" : "flag",
    liveDot: reddish(team.dark) ? "#000000" : "#ff2d2d",
    mode,
    matchLen: matchLengthMin,
  };

  return `// ===== World Cup MatchDay Widget =====
// Generated by matchday-widget. Paste into Scriptable, name it "World Cup",
// then add a Scriptable widget to your home/lock screen and pick this script.

// 👇 PASTE A LINK TO YOUR OWN HIGH-QUALITY WORLD CUP IMAGE HERE (PNG/JPG).
//    Leave it as-is to use the default photo.
const CUP_IMAGE = ${JSON.stringify(cupImage)};

// ============================================================
// 🔍 CUP IMAGE ZOOM  —  change ONE number to resize the picture.
//    Bigger number = bigger picture (zoom in). Smaller = zoom out.
//    1 = default. Try 1.3, 1.6, 2 ... This only scales the picture;
//    it is INDEPENDENT of the widget / background size.
// ============================================================
const CUP_ZOOM = 1;
const CUP_BASE_W = 82;   // base picture width  in points (before zoom)
const CUP_BASE_H = 128;  // base picture height in points (before zoom)

const CFG = ${JSON.stringify(cfg, null, 2)};
const TEAMS = ${JSON.stringify(T)};
const FIXTURES = ${JSON.stringify(slim)};

// ---- helpers (mirror the website logic) ----
function endOf(m) { return new Date(new Date(m.k).getTime() + CFG.matchLen * 60000); }
function nameOf(c) { return (TEAMS[c] && TEAMS[c].n) || c; }
function flagOf(c) { return (TEAMS[c] && TEAMS[c].f) || ""; }

function dayKey(date) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: CFG.tz, year: "numeric", month: "2-digit", day: "2-digit",
  }).format(date);
}
function localHour(date) {
  return Number(new Intl.DateTimeFormat("en-GB", {
    timeZone: CFG.tz, hour: "2-digit", hour12: false,
  }).format(date));
}
function fmtTime(date) {
  return new Intl.DateTimeFormat("en-US", {
    timeZone: CFG.tz, hour: "numeric", minute: "2-digit", hour12: true,
  }).format(date).toLowerCase();
}
function dayLabel(now, kickoff) {
  const k = new Date(kickoff);
  const dk = dayKey(k), tk = dayKey(now);
  const h = localHour(k);
  if (dk === tk) return h < 6 ? "Tonight" : "Today";
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: CFG.tz, day: "numeric", month: "short",
  }).format(k); // e.g. "17 Jun"
}

function compute(now) {
  let pool = FIXTURES.slice();
  if (CFG.mode === "team") {
    pool = pool.filter(m => m.h === CFG.teamCode || m.a === CFG.teamCode);
  }
  pool.sort((a, b) => new Date(a.k) - new Date(b.k));
  let selected;
  if (CFG.mode === "team") {
    // Follow my team: the team's next upcoming matches, rolling forward.
    selected = pool.filter(m => endOf(m) > now);
  } else {
    // All matches: only TODAY and TOMORROW; rolls forward as matches finish.
    const todayK = dayKey(now);
    const tomorrowK = dayKey(new Date(now.getTime() + 864e5));
    selected = pool.filter(m => {
      if (endOf(m) <= now) return false;
      const dk = dayKey(new Date(m.k));
      return dk === todayK || dk === tomorrowK;
    });
  }
  if (!selected.length) return { empty: true };
  return {
    empty: false,
    matches: selected.map(m => {
      const start = new Date(m.k), end = endOf(m);
      const live = now >= start && now < end;
      return {
        home: m.h, away: m.a, live,
        when: dayLabel(now, m.k) + " · " + fmtTime(start),
      };
    }),
  };
}

async function loadCup() {
  try { return await new Request(CUP_IMAGE).loadImage(); }
  catch (e) { return null; }
}
async function loadFlag() {
  try { return await new Request(CFG.flag).loadImage(); }
  catch (e) { return null; }
}
// glassmorphic background: upscale the small flag (=> soft blur) + tint
function glassBg(flagImg) {
  if (!flagImg) return null;
  const W = 360, H = 180;
  const ctx = new DrawContext();
  ctx.size = new Size(W, H);
  ctx.opaque = false;
  ctx.respectScreenScale = true;
  ctx.drawImageInRect(flagImg, new Rect(-30, -30, W + 60, H + 60)); // overscan upscale -> blur
  ctx.setFillColor(new Color(CFG.bg, 0.34));    // team-colour tint
  ctx.fillRect(new Rect(0, 0, W, H));
  ctx.setFillColor(new Color("#000000", 0.30)); // darken for readable text
  ctx.fillRect(new Rect(0, 0, W, H));
  return ctx.getImage();
}

// ---- build the widget ----
async function buildWidget() {
  const now = new Date();
  const r = compute(now);
  const fg = new Color(CFG.fg);
  const cupImg = await loadCup();
  const bgImg = CFG.bgStyle === "solid" ? null : glassBg(await loadFlag());

  // Medium widget fits 4 small rows; Large fits more; Small fits 2.
  const FAMILY = (config.runsInWidget && config.widgetFamily) ? config.widgetFamily : "medium";
  const CAP = FAMILY === "large" ? 6 : FAMILY === "small" ? 2 : 4;

  const w = new ListWidget();
  w.backgroundColor = new Color(CFG.border); // light colour = border ring
  w.setPadding(6, 6, 6, 6);                  // border thickness

  const card = w.addStack();
  card.layoutHorizontally();
  card.backgroundColor = new Color(CFG.bg);  // fallback if the flag fails to load
  if (bgImg) card.backgroundImage = bgImg;   // blurred flag + glass tint
  card.cornerRadius = 16;
  card.setPadding(0, 0, 0, 0);

  // left art panel — cup picture, scaled by CUP_ZOOM (independent of widget size)
  const art = card.addStack();
  art.layoutVertically();
  art.setPadding(6, 8, 6, 4);
  art.addSpacer();
  if (cupImg) {
    const im = art.addImage(cupImg);
    im.applyFillingContentMode();          // fill the box (zoom-crop, no distortion)
    im.imageSize = new Size(CUP_BASE_W * CUP_ZOOM, CUP_BASE_H * CUP_ZOOM);
    im.cornerRadius = 8;
    im.centerAlignImage();
  } else {
    const tr = art.addText("🏆");
    tr.font = Font.systemFont(30 * CUP_ZOOM);
    tr.centerAlignText();
  }
  art.addSpacer();

  // right body — matches only (no header), centred, small font => fits 4
  const body = card.addStack();
  body.layoutVertically();
  body.setPadding(8, 6, 8, 12);
  body.addSpacer();

  if (r.empty) {
    const e = body.addText("No upcoming matches.");
    e.font = Font.systemFont(12);
    e.textColor = fg;
    e.centerAlignText();
  } else {
    const shown = r.matches.slice(0, CAP);
    shown.forEach((m, i) => {
      const teams = body.addText(
        flagOf(m.home) + " " + nameOf(m.home) + "  vs  " + flagOf(m.away) + " " + nameOf(m.away)
      );
      teams.font = Font.boldSystemFont(11);
      teams.textColor = fg;
      teams.lineLimit = 1;
      teams.centerAlignText();
      body.addSpacer(2);

      if (m.live) {
        // a dot just beside the word LIVE, centred beneath the teams
        const lr = body.addStack();
        lr.layoutHorizontally();
        lr.centerAlignContent();
      
        const dot = lr.addText("●");
        dot.font = Font.systemFont(6);
        dot.textColor = new Color(CFG.liveDot);
        lr.addSpacer(4);
        const lt = lr.addText("LIVE");
        lt.font = Font.boldSystemFont(8);
        lt.textColor = fg;
        lr.addSpacer();
      } else {
        const when = body.addText(m.when);
        when.font = Font.mediumSystemFont(9);
        when.textColor = fg;
        when.textOpacity = 0.85;
        when.centerAlignText();
      }

      if (i < shown.length - 1) body.addSpacer(8); // equal spacing between matches
    });
    const extra = r.matches.length - shown.length;
    if (extra > 0) {
      body.addSpacer(5);
      const more = body.addText("+ " + extra + " more");
      more.font = Font.systemFont(9);
      more.textColor = fg;
      more.textOpacity = 0.75;
      more.centerAlignText();
    }
  }
  body.addSpacer();

  
  let nextRefresh = new Date(now.getTime() + 45 * 60 * 1000); // 1 hour cap
  for (const m of FIXTURES) {
    const start = new Date(m.k);
    const end = endOf(m);
    if (start > now && start < nextRefresh) nextRefresh = start;
    if (end > now && end < nextRefresh) nextRefresh = end;
  }
  w.refreshAfterDate = nextRefresh;

  return w;
}

const widget = await buildWidget();
if (config.runsInWidget) {
  Script.setWidget(widget);
} else {
  // In-app preview shows the Large layout (all of the day's matches).
  await widget.presentLarge();
}
Script.complete();
`;
}
